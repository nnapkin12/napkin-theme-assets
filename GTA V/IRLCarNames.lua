-- RealNames.lua
-- Stand script for GTA V Story Mode (Legacy).
-- Replaces in-game vehicle and weapon GXT labels with real-life names.
--
-- Original list: harleenquinzzel, thanks xm4ddy.
-- This rewrite drops the broken auto-updater (that was the soup.json.encode
-- crash and the 'unexpected symbol near end' error at the DCN warning).
-- Label keys are the game's gameName GXTs. Several models share one label.
--
-- Install: copy this file into Stand/Lua Scripts and run it.
-- Commands: rcn (cars on), rwn (weapons on), dcn / dwn (restore).

local SCRIPT_VERSION = "4.0.0"

local function clean_name(text)
    text = text or ""
    text = text:gsub(";", ",")
    text = text:gsub('"', "'")
    return text
end

local function apply_labels(entries)
    for i, data in ipairs(entries) do
        local key = data[1]
        local name = clean_name(data[2])
        if name == "" then
            name = " "
        end
        menu.trigger_commands("addlabel " .. key)
        menu.trigger_commands("edit" .. key .. " " .. name)
        if i % 10 == 0 then
            util.yield()
        end
    end
end

local function remove_labels(entries)
    for i, data in ipairs(entries) do
        menu.trigger_commands("remove" .. data[1])
        if i % 10 == 0 then
            util.yield()
        end
    end
end

