    menu.show_warning(restore, click_type, "Restore vanilla vehicle names?", function()
        util.toast("Restoring vehicle names...")
        remove_labels(cars)
        util.toast("Vehicle names restored.")
    end, function()
        util.toast("Cancelled.")
    end, false)
end)

